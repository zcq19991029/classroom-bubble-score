const assert = require('node:assert/strict');
const vm = require('node:vm');
const source = require('node:fs').readFileSync(require('node:path').join(__dirname, '..', 'grouping-model.js'), 'utf8');
const context = { window: {} };
vm.runInNewContext(source, context);
const M = context.window.GroupingModel;
const students = [{ id: 'a', studentNo: '001', name: '甲' }, { id: 'b', studentNo: '002', name: '乙' }, { id: 'c', studentNo: '003', name: '丙' }];
const state = M.create(students, 2, 1);
assert.equal(state.locked, true);
assert.deepEqual(Array.from(state.unassignedIds), ['a', 'b', 'c']);
M.add(state, 'a', 'group-1');
assert.throws(() => M.add(state, 'b', 'group-1'), /人数上限/);
M.add(state, 'b', 'group-2');
state.groups[1].max = 2;
M.add(state, 'a', 'group-2');
assert.deepEqual(Array.from(state.groups[1].studentIds), ['b', 'a']);
assert.deepEqual(Array.from(state.unassignedIds), ['c']);
M.leader(state, 'group-2', 'b');
assert.equal(state.groups[1].leaderId, 'b');
M.remove(state, 'b');
assert.equal(state.groups[1].leaderId, null);
assert.deepEqual(Array.from(state.unassignedIds).sort(), ['b', 'c']);
M.role(state, '班长', 'a');
assert.equal(state.committee['班长'], 'a');
const normalized = M.normalize({ locked: false, groups: [{ id: 'group-1', max: 4, studentIds: ['a'], leaderId: 'a' }], committee: { 班长: 'a' } }, students);
assert.equal(normalized.locked, false);
assert.equal(normalized.groups[0].leaderId, 'a');
assert.equal(normalized.committee['班长'], 'a');
console.log('grouping model tests: pass');
